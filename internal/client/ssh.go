// SSH runs the system OpenSSH client for one host. It never edits ~/.ssh/config:
// it passes a generated config that includes the user's own.
type SSH struct {
	Host Host
	// Interactive allows prompts (passwords, host keys, FIDO touches).
	Interactive bool
}

func home() string { h, _ := os.UserHomeDir(); return h }

// wrapperPath is the generated SSH config for one host.
func wrapperPath(h Host) string {
	return filepath.Join(ConfigDir(), "ssh", "config-"+h.Name)
}

// writeWrapper writes the generated SSH config for h. Order matters, because
// ssh uses the first value it finds: the host's own config first, then the
// user's, then the system's, then our defaults.
func writeWrapper(h Host) (string, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by %s for host %q. Do not edit; it is rewritten on each run.\n", brand.Name, h.Name)
	if h.SSHConfig != "" {
		p := expand(h.SSHConfig)
		if _, err := os.Stat(p); err != nil {
			return "", &UserError{Msg: fmt.Sprintf("the SSH config %s for host %s is missing", p, h.Name), Hint: brand.Name + " host edit " + h.Name}
		}
		fmt.Fprintf(&b, "Include %q\n", p)
	}
	if p := filepath.Join(home(), ".ssh", "config"); exists(p) {
		fmt.Fprintf(&b, "Include %q\n", p)
	}
	if exists("/etc/ssh/ssh_config") {
		b.WriteString("Include /etc/ssh/ssh_config\n")
	}
	b.WriteString("Host *\n")
	b.WriteString("    ServerAliveInterval 10\n")
	b.WriteString("    ServerAliveCountMax 3\n")
	b.WriteString("    ConnectTimeout 15\n")
	path := wrapperPath(h)
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return "", err
	}
	if old, err := os.ReadFile(path); err == nil && string(old) == b.String() {
		return path, nil
	}
	return path, os.WriteFile(path, []byte(b.String()), 0o600)
}

func exists(p string) bool { _, err := os.Stat(p); return err == nil }

func expand(p string) string {
	if rest, ok := strings.CutPrefix(p, "~/"); ok {
		return filepath.Join(home(), rest)
	}
	return p
}

// controlPath is short, because macOS limits socket paths to 104 bytes.
func controlPath() string { return filepath.Join(CacheDir(), "cm", "%C") }

func (s *SSH) baseArgs() ([]string, error) {
	cfg, err := writeWrapper(s.Host)
	if err != nil {
		return nil, err
	}
	if err := os.MkdirAll(filepath.Join(CacheDir(), "cm"), 0o700); err != nil {
		return nil, err
	}
	args := []string{"-F", cfg,
		"-o", "ControlMaster=auto",
		"-o", "ControlPath=" + controlPath(),
		"-o", "ControlPersist=600",
	}
	if !s.Interactive {
		args = append(args, "-o", "BatchMode=yes")
	}
	return args, nil
}

// RemoteHelper is the helper path for a version, in the remote shell's syntax.
func RemoteHelper(ver string) string {
	return fmt.Sprintf(`"$HOME/.local/share/%s/bin/%s/%s"`, brand.Name, ver, brand.HostBinary)
}

// Command builds an ssh command that runs remote (a shell command line) on the host.
func (s *SSH) Command(ctx context.Context, remote string, extra ...string) (*exec.Cmd, error) {
	args, err := s.baseArgs()
	if err != nil {
		return nil, err
	}
	args = append(args, extra...)
	args = append(args, "-e", "none", "--", s.Host.SSH, remote)
	cmd := exec.CommandContext(ctx, "ssh", args...)
	cmd.WaitDelay = 2 * time.Second
	return cmd, nil
}

// Run runs a remote command and returns its stdout. The error includes stderr.
func (s *SSH) Run(ctx context.Context, remote string, stdin io.Reader) ([]byte, error) {
	cmd, err := s.Command(ctx, remote, "-T")
	if err != nil {
		return nil, err
	}
	var out, errb bytes.Buffer
	cmd.Stdin = stdin
	cmd.Stdout = &out
	if s.Interactive {
		cmd.Stderr = io.MultiWriter(&errb, os.Stderr)
	} else {
		cmd.Stderr = &errb
	}
	if err := cmd.Run(); err != nil {
		return out.Bytes(), sshError(s.Host, err, errb.String())
	}
	return out.Bytes(), nil
}

// ExitMaster stops the ControlMaster for this host. Call it before reconnecting
// after a network change, because a master on a dead TCP connection hangs new sessions.
func (s *SSH) ExitMaster() {
	args, err := s.baseArgs()
	if err != nil {
		return
	}
	args = append(args, "-O", "exit", s.Host.SSH)
	cmd := exec.Command("ssh", args...)
	cmd.Stdout, cmd.Stderr = io.Discard, io.Discard
	_ = cmd.Run()
}

// sshError turns ssh's exit status and stderr into a user error.
func sshError(h Host, err error, stderr string) error {
	msg := strings.TrimSpace(stderr)
	if lines := strings.Split(msg, "\n"); len(lines) > 3 {
		msg = strings.Join(lines[len(lines)-3:], "\n")
	}
	var ee *exec.ExitError
	if ok := asExit(err, &ee); ok && ee.ExitCode() == 255 {
		if msg == "" {
			msg = "ssh failed"
		}
		return &UserError{Msg: fmt.Sprintf("cannot reach %s: %s", h.Name, msg), Hint: fmt.Sprintf("ssh %s   (check that this works first)", h.SSH)}
	}
	if msg == "" {
		return err
	}
	return fmt.Errorf("%w: %s", err, msg)
}

func asExit(err error, target **exec.ExitError) bool {
	return errors.As(err, target)
}

// Forward builds an ssh command that forwards local ports to the host until it
// is stopped. Each pair maps a local port to an address and port on the host.
func (s *SSH) Forward(ctx context.Context, pairs []ForwardPair) (*exec.Cmd, error) {
	args, err := s.baseArgs()
	if err != nil {
		return nil, err
	}
	args = append(args, "-N", "-o", "ExitOnForwardFailure=yes")
	for _, p := range pairs {
		args = append(args, "-L", fmt.Sprintf("127.0.0.1:%d:%s:%d", p.Local, p.RemoteHost, p.Remote))
	}
	args = append(args, "--", s.Host.SSH)
	return exec.CommandContext(ctx, "ssh", args...), nil
}

// ForwardPair is one forwarded port.
type ForwardPair struct {
	Local      int
	RemoteHost string
	Remote     int
}
